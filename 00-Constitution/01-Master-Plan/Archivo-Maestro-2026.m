# Archivo Maestro de Operaciones 2026

### 1. Visión General
BajaRide es un marketplace especializado en la renta y gestión de vehículos UTV y ATV, diseñado para optimizar la experiencia de aventura en la región de Baja California, conectando operadores con entusiastas del off-road de manera ágil y segura.

### 2. Objetivos Estratégicos 2026
* **Infraestructura Core**: Consolidar el repositorio central y definir la arquitectura de software definitiva.
* **Ecosistema Digital**: Desarrollar la aplicación móvil utilizando Flutter para garantizar un despliegue multiplataforma eficiente.
* **Integración Operativa**: Sincronizar el almacenamiento técnico de GitHub con el almacenamiento de recursos pesados (PDFs, contratos, multimedia) en Google Drive.

### 3. Core Tecnológico
* **Frontend/Mobile**: Flutter / Dart.
* **Backend/API**: Arquitectura escalable (Node.js / TypeScript).
* **Gestión de Datos**: Estructuras de alta disponibilidad y caché para mapas y disponibilidad en tiempo real.
